import { expect, type Browser, type Page } from "@playwright/test";

/**
 * With Cache Components, Next.js keeps recently visited routes mounted but hidden
 * (React <Activity>), so label/text queries only consider visible elements.
 */
export const L = (page: Page, label: string | RegExp, opts?: { exact?: boolean }) => page.getByLabel(label, opts).filter({ visible: true });
export const T = (page: Page, text: string | RegExp, opts?: { exact?: boolean }) => page.getByText(text, opts).filter({ visible: true }).first();
import { createHash, randomBytes } from "node:crypto";
import pg from "pg";

const url = process.env.E2E_DATABASE_URL ?? "postgresql://hub:hub@localhost:5432/collab_hub_e2e";

export async function query<T extends pg.QueryResultRow>(sql: string, params: unknown[] = []) {
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    return (await client.query<T>(sql, params)).rows;
  } finally {
    await client.end();
  }
}

export const uid = () => Math.random().toString(36).slice(2, 8);

/** `username` is generated by the server from the name; it's filled in by signUpAndVerify. */
export type TestAccount = { name: string; username: string; email: string; password: string };

export function account(prefix: string, name: string): TestAccount {
  return { name, username: "", email: `${prefix}-${uid()}@e2e.test`, password: "e2e password long enough" };
}

/** Signs up through the UI (name, email, password) and confirms the email using the link from the outbox. */
export async function signUpAndVerify(page: Page, a: TestAccount) {
  // The suite signs up many people from one IP against a production build, where the real
  // limit (5 signups per hour per IP) applies. Reset only that counter, in the e2e database,
  // so the app's limit itself stays untouched.
  await query(`DELETE FROM "RateLimit" WHERE key LIKE 'signup:%'`);
  await page.goto("/signup");
  await L(page, "Name", { exact: true }).fill(a.name);
  await L(page, "Email").fill(a.email);
  await L(page, "Password").fill(a.password);
  await page.getByRole("button", { name: "Create account" }).click();
  await page.waitForURL(/\/profile\/edit/);
  await expect(page.getByRole("heading", { name: "Set up your profile" })).toBeVisible();
  const [user] = await query<{ username: string }>(`SELECT username FROM "User" WHERE email = $1`, [a.email]);
  expect(user?.username, "generated username").toBeTruthy();
  a.username = user!.username;

  // The verification email was queued; production builds keep no body in the outbox (no
  // links at rest), so the test issues its own token the same way the server does (only the
  // SHA-256 hash is stored) and follows the real /verify-email page.
  const queued = await query<{ n: string }>(`SELECT count(*) AS n FROM "EmailOutbox" WHERE "to" = $1 AND kind = 'verify-email'`, [a.email]);
  expect(Number(queued[0]?.n), "verification email queued").toBeGreaterThan(0);
  const token = randomBytes(32).toString("base64url");
  await query(
    `INSERT INTO "AuthToken" (id, "userId", type, "tokenHash", "expiresAt") SELECT $1, id, 'EMAIL_VERIFY', $2, now() + interval '1 hour' FROM "User" WHERE email = $3`,
    [`e2e-${uid()}${uid()}`, createHash("sha256").update(token).digest("hex"), a.email],
  );
  await page.goto(`/verify-email?token=${token}`);
  await page.getByRole("button", { name: "Confirm my email" }).click();
  await page.waitForURL(/\/feed/);
}

export async function signIn(page: Page, a: TestAccount) {
  await page.goto("/login");
  await L(page, "Email").fill(a.email);
  await L(page, "Password").fill(a.password);
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.waitForURL(/\/feed/);
}

export async function newUserPage(browser: Browser) {
  const ctx = await browser.newContext();
  return ctx.newPage();
}

/** Adds tags through the TagInput combobox. */
export async function addTags(page: Page, label: RegExp | string, tags: string[]) {
  const input = page.getByRole("combobox", { name: label }).filter({ visible: true });
  for (const t of tags) {
    await input.fill(t);
    await input.press("Enter");
  }
}

export async function expectToast(page: Page, text: string | RegExp) {
  await expect(page.getByRole("status").filter({ hasText: text }).first()).toBeVisible();
}

/** Types into the position combobox and picks the option with that exact label. */
export async function pickPosition(page: Page, typed: string, label: string, field: string | RegExp = /^Position you're looking for/) {
  const box = page.getByRole("combobox", { name: field }).filter({ visible: true });
  await box.fill(typed);
  await page.getByRole("option", { name: new RegExp(`^${label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`) }).first().click();
}
